export function useDepartments(facultyId?: string) {
  const [departments, setDepartments] = useState<Department[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const fetchDepartments = async () => {
    try {
      setLoading(true);
      setError(null);
      const response = await apiService.getDepartments(facultyId) as any;
      setDepartments(response.results || response);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Xatolik yuz berdi');
      console.error('Departments fetch error:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchDepartments();
  }, [facultyId]);

  const addDepartment = async (department: Omit<Department, 'id'>) => {
    try {
      const newDepartment = await apiService.createDepartment(department) as any;
      setDepartments(prev => [...prev, newDepartment]);
      return newDepartment;
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Kafedra yaratishda xatolik');
      throw err;
    }
  };

  const updateDepartment = async (id: string, updates: Partial<Department>) => {
    try {
      const updatedDepartment = await apiService.updateDepartment(id, updates) as any;
      setDepartments(prev => 
        prev.map(department => 
          department.id === id ? updatedDepartment : department
        )
      );
      return updatedDepartment;
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Kafedra yangilashda xatolik');
      throw err;
    }
  };

  const deleteDepartment = async (id: string) => {
    try {
      await apiService.deleteDepartment(id);
      setDepartments(prev => prev.filter(department => department.id !== id));
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Kafedra o\'chirishda xatolik');
      throw err;
    }
  };

  return {
    departments,
    loading,
    error,
    addDepartment,
    updateDepartment,
    deleteDepartment,
    refresh: fetchDepartments
  };
}

