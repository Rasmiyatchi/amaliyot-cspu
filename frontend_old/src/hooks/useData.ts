// Amaliyotlar hook
export function useInternships() {
  const [internships, setInternships] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const fetchInternships = async () => {
    try {
      setLoading(true);
      setError(null);
      const response = await apiService.getInternships() as any;
      const internshipsData = response.results || response;
      setInternships(internshipsData);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Amaliyotlar yuklashda xatolik');
      console.error('Internships fetch error:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchInternships();
  }, []);

  const getStudentInternship = (studentId: string | number) => {
    const studentIdNum = typeof studentId === 'string' ? parseInt(studentId) : studentId;
    
    const found = internships.find(internship => {
      const internshipStudentId = typeof internship.student === 'object' 
        ? internship.student?.id 
        : internship.student;
      
      return internshipStudentId == studentIdNum || internshipStudentId == studentId;
    });
    
    return found;
  };

  return { 
    internships, 
    loading, 
    error, 
    getStudentInternship,
    refresh: fetchInternships 
  };
}